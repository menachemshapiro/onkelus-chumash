def parts(lst):
    out = []
    for x in lst:
        kind = 'g' if '~' in x and ('=' not in x or x.index('~') < x.index('=')) else 'w'
        txt, m = x.split('~' if kind == 'g' else '=', 1)
        # a piece that starts with a vowel sign is shown on a dotted circle (◌ֵהּ) instead of after a maqaf
        if txt.startswith('־') and len(txt) > 1 and '\u0591' <= txt[1] <= '\u05c7': txt = '◌' + txt[1:]
        out.append([txt, m, kind])
    return out

